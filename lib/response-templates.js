export function suggestResponses(category, urgency) {
  const cat = CATEGORIES.includes(category) ? category : '기타';
  const urg = urgency === 'high' || urgency === 'low' ? urgency : 'mid';
  const base = BASE_TEMPLATES[cat];

  if (urg === 'high') {
    return [URGENT_LEAD[cat], base[0]];
  }
  if (urg === 'low') {
    return [POSITIVE_LINE[cat], base[0]];
  }
  return [...base];
}
